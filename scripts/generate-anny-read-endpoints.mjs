#!/usr/bin/env node
// Regenerates src/providers/anny/read-endpoints.generated.ts from anny's
// published OpenAPI specs. Only GET operations that neither carry an action
// segment nor describe a side effect in their summary end up on the list.
// Several anny GET routes mutate data (cancel, send, set-paid, "get or
// create" …), so the HTTP method alone never decides whether a call is a read.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SPECS = ["admin", "customer"].map(
  (name) => `https://docs.anny.co/developers/openapi/${name}.openapi.json`,
);

/** Path segments that name an action rather than a resource or relation. */
const ACTION_SEGMENTS = [
  "accept-invite",
  "calculate",
  "cancel",
  "cancel-edit-booking",
  "change-recipient",
  "check-in",
  "check-out",
  "claim",
  "delete-all",
  "duplicate",
  "edit",
  "export",
  "extend",
  "from-config",
  "generate-file",
  "leave",
  "merge",
  "move-to-balance",
  "pair",
  "preview",
  "regenerate-certificate",
  "remove-from-community",
  "remove-recent-entity",
  "request-deletion",
  "resend",
  "resend-mail",
  "retry",
  "revoke",
  "run",
  "send",
  "send-notification",
  "set-paid",
  "start",
  "stop",
  "sync-auto-join",
  "sync-quotas",
  "test-connection",
  "translate-model",
  "unpair",
];

// Verbs like "start" or "run" stay out: availability summaries say "start
// times". Those actions are caught by ACTION_SEGMENTS instead.
const SIDE_EFFECT_SUMMARY =
  /\b(create|cancel|send|delete|remove|revoke|claim|leave|resend|re-send|duplicate|pair|unpair|sync|accept|regenerate|trigger|merge|clear)\b/i;

const AVAILABILITY_PREFIXES = ["/api/v1/availability/", "/api/v1/intervals/"];

/** The customer cart ("GET /order" creates one) is never a read. */
const EXCLUDED_PREFIXES = ["/api/v1/order/", "/api/v1/order"];

const templates = new Map();
// Every fixed segment anny uses anywhere ("instant", "export", "checkout" …).
// "{}" must never match one: GET /bookings/instant is not a booking read.
const literals = new Set();
for (const url of SPECS) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const spec = await res.json();
  for (const [path, ops] of Object.entries(spec.paths)) {
    for (const segment of path.split("/")) if (segment && !segment.startsWith("{")) literals.add(segment);
    const get = ops.get;
    if (!get || !path.startsWith("/api/v1/")) continue;
    if (EXCLUDED_PREFIXES.some((p) => path === p || path.startsWith(`${p}/`))) continue;
    const segments = path.split("/").filter(Boolean);
    // The public availability engine names its queries "start"/"end"; none of
    // them change data, so action segments are not checked below it.
    const isAvailability = AVAILABILITY_PREFIXES.some((p) => path.startsWith(p));
    if (!isAvailability && segments.some((s) => ACTION_SEGMENTS.includes(s))) continue;
    if (SIDE_EFFECT_SUMMARY.test(get.summary ?? "")) continue;
    const template = segments.map((s) => (s.startsWith("{") ? "{}" : s)).join("/");
    if (!templates.has(template)) templates.set(template, get.summary ?? "");
  }
}

const sorted = [...templates.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = sorted.map(([t, summary]) => `  ["/${t}", ${JSON.stringify(summary)}],`).join("\n");
const out = `// Generated by scripts/generate-anny-read-endpoints.mjs — do not edit by hand.
// Source: ${SPECS.join(", ")}
// "{}" matches exactly one path segment (an ID or slug).

export const READ_ENDPOINTS: readonly (readonly [template: string, summary: string])[] = [
${body}
];

/**
 * Fixed path segments of the anny API plus known action names; "{}" (an ID
 * or slug) never matches one of them, so e.g. /bookings/instant or
 * /bookings/export is not mistaken for /bookings/{id}.
 */
export const RESERVED_SEGMENTS: ReadonlySet<string> = new Set([
${[...new Set([...literals, ...ACTION_SEGMENTS])]
  .sort()
  .map((s) => `  ${JSON.stringify(s)},`)
  .join("\n")}
]);
`;
const target = fileURLToPath(
  new URL("../src/providers/anny/read-endpoints.generated.ts", import.meta.url),
);
writeFileSync(target, out);
console.log(`${String(sorted.length)} read endpoints → ${target}`);
